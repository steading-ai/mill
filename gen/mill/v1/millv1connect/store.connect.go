// StoreServiceHandler is an implementation of the mill.v1.StoreService service.
type StoreServiceHandler interface {
	// GetRunByNode returns the live run for a dagger node, or nothing. The
	// first call a worker makes after a claim.
	GetRunByNode(context.Context, *connect.Request[v1.GetRunByNodeRequest]) (*connect.Response[v1.GetRunByNodeResponse], error)
	// CreateRun opens a run on a node in status selecting. At most one live
	// run per node; the store rejects a second.
	CreateRun(context.Context, *connect.Request[v1.CreateRunRequest]) (*connect.Response[v1.CreateRunResponse], error)
	// SetLease makes a claim's lease the run's current one, so every later
	// write is fenced by it.
	SetLease(context.Context, *connect.Request[v1.SetLeaseRequest]) (*connect.Response[v1.SetLeaseResponse], error)
	// StartStepRun opens the next attempt at a step, numbering it max+1 for
	// the (run, step) pair. At most one running attempt per run.
	StartStepRun(context.Context, *connect.Request[v1.StartStepRunRequest]) (*connect.Response[v1.StartStepRunResponse], error)
	// CloseStepRun records the evidence that closes an attempt and marks it
	// closed, in one transaction. The only way a step becomes closed.
	CloseStepRun(context.Context, *connect.Request[v1.CloseStepRunRequest]) (*connect.Response[v1.CloseStepRunResponse], error)
	// FailStepRun marks an attempt failed with how its process ended, so the
	// step's on_failure can be applied.
	FailStepRun(context.Context, *connect.Request[v1.FailStepRunRequest]) (*connect.Response[v1.FailStepRunResponse], error)
	// AbortOpenStepRuns marks any still-running attempt aborted. Called on
	// resume, when a running row belongs to a dead or fenced-out worker.
	AbortOpenStepRuns(context.Context, *connect.Request[v1.AbortOpenStepRunsRequest]) (*connect.Response[v1.AbortOpenStepRunsResponse], error)
	// SupersedeSteps marks the latest attempts of every step from a target
	// through a failing step superseded, which is what moves current_step
	// backwards for a revise.
	SupersedeSteps(context.Context, *connect.Request[v1.SupersedeStepsRequest]) (*connect.Response[v1.SupersedeStepsResponse], error)
	// MarkWaiting records the gate a run is blocked on and marks it waiting.
	// Called between the patch that files the gate and the release, so a crash
	// never leaves a gate the store would file twice.
	MarkWaiting(context.Context, *connect.Request[v1.MarkWaitingRequest]) (*connect.Response[v1.MarkWaitingResponse], error)
	// Park trips the circuit breaker: the run stops, a gate asks a human what
	// to do, and the reason says what stopped it.
	Park(context.Context, *connect.Request[v1.ParkRequest]) (*connect.Response[v1.ParkResponse], error)
	// Done marks a run done. Called only after dagger has confirmed the
	// completing patch: a run marked done before that would strand a node
	// nothing can claim.
	Done(context.Context, *connect.Request[v1.DoneRequest]) (*connect.Response[v1.DoneResponse], error)
	// Abandon marks a run abandoned so a new generation can be created. The
	// restart path, and the only caller of it is a human.
	Abandon(context.Context, *connect.Request[v1.AbandonRequest]) (*connect.Response[v1.AbandonResponse], error)
	// IssueStepToken mints the step-scoped bearer a session presents on the
	// workspace socket. The bearer is returned once; the store keeps its hash.
	IssueStepToken(context.Context, *connect.Request[v1.IssueStepTokenRequest]) (*connect.Response[v1.IssueStepTokenResponse], error)
	// RevokeStepToken revokes a bearer. Written in the same transaction that
	// moves its step run out of running.
	RevokeStepToken(context.Context, *connect.Request[v1.RevokeStepTokenRequest]) (*connect.Response[v1.RevokeStepTokenResponse], error)
	// RecordUsage appends what a turn cost, per model, to the ledger.
	RecordUsage(context.Context, *connect.Request[v1.RecordUsageRequest]) (*connect.Response[v1.RecordUsageResponse], error)
	// MarkUsagePosted marks a step run's usage rows as posted to dagger, after
	// ReportUsage has accepted them.
	MarkUsagePosted(context.Context, *connect.Request[v1.MarkUsagePostedRequest]) (*connect.Response[v1.MarkUsagePostedResponse], error)
	// GetWorkflow returns one workflow version, by id or by name in a scope.
	GetWorkflow(context.Context, *connect.Request[v1.GetWorkflowRequest]) (*connect.Response[v1.GetWorkflowResponse], error)
	// ListWorkflows lists workflow versions in a scope, newest first.
	ListWorkflows(context.Context, *connect.Request[v1.ListWorkflowsRequest]) (*connect.Response[v1.ListWorkflowsResponse], error)
	// PutWorkflow stores a workflow version. Idempotent by content hash:
	// storing the same definition twice returns the existing version.
	PutWorkflow(context.Context, *connect.Request[v1.PutWorkflowRequest]) (*connect.Response[v1.PutWorkflowResponse], error)
	// PutSkill stores a skill by name and digest, so a workflow version pins
	// the exact prompt it ran. Idempotent by digest.
	PutSkill(context.Context, *connect.Request[v1.PutSkillRequest]) (*connect.Response[v1.PutSkillResponse], error)
	// Status lists runs by state with what the ledger derives: current step,
	// cost, and the gate a waiting run is blocked on.
	Status(context.Context, *connect.Request[v1.StatusRequest]) (*connect.Response[v1.StatusResponse], error)
	// Inspect returns one run's every attempt in order with its evidence,
	// exit, session, and usage.
	Inspect(context.Context, *connect.Request[v1.InspectRequest]) (*connect.Response[v1.InspectResponse], error)
}

