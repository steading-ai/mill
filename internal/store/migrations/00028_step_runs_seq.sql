-- ListStepRuns orders by started_at, then a tiebreak. id (a ULID) was that
-- tiebreak, but its monotonic-within-a-process guarantee (internal/store/ulid.go)
-- is not a schema-level one: it does not hold across a process resume. seq
-- does, unconditionally, because the database assigns it at insert.
--
-- An identity column rather than bigserial: identity columns route their
-- privilege checks through the owning table's grants, so the existing
-- INSERT grant on step_runs (00012_grants.sql) is enough. bigserial creates
-- a separate sequence object mill_app has no USAGE on, which would fail
-- every InsertStepRun under that role.
--
-- Safe to apply after a later migration: it only adds a column nothing
-- numbered above it reads or writes.
-- +mill out-of-order: safe

-- +goose Up

ALTER TABLE step_runs ADD COLUMN seq bigint GENERATED BY DEFAULT AS IDENTITY;

